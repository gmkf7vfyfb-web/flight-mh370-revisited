#!/usr/bin/env python3
"""Store memory rows that move out of memory (memory track, 25 Oct 2026) as registry notes and citation-ledger rows.

These are RECORDS OF WHAT MEMORY SAID. They are not verified facts. Each row keeps its mem_id, the original text (from the
memory export), and the verification status that the memory track gave it.

Inputs (platform artifacts; give the local paths):
  --export    memory-export-2026-10-25.jsonl (artifact version ba131e4c-350c-4db5-8b56-a61b3f2772f9; SHA-256 starts efbc74bc)
  --changes   memory-changes-2026-10-25.csv (version 222ef8d7-...)  rows with action move-to-registry / move-to-citation-ledger
  --facts     memory-external-facts-verification-2026-10-25.csv (version 741d4623-...)
Outputs:
  memory-notes/<topic>.jsonl, memory-notes/index.json, memory-notes/README.md (registry side)
  a generated section in each results/<module>-references.md (and paper/JON-RULES.md) between the markers below.
Rules:
  * Hydroacoustics rows are not written (phase 2): move-to-registry rows whose target is on hypothesis/hydroacoustics, and
    citation rows whose ledger is results/hydroacoustics-references.md.
  * Text that names a restricted source (FPPM, internal-v1, fuel-tables.json, Ulich, MH371 ACARS/EHM, avionics training files,
    'confidential') is withheld: the repository is public. The row keeps its mem_id and a pointer to the export row.
  * Session-workspace paths are replaced by '<session workspace path>'. Spending amounts are replaced by '<amount removed>'.
  * The independent verifier's six external-fact findings of 25 Oct 2026 are applied (VERIFIER_FIXES below).
"""
import argparse, collections, csv, hashlib, json, re
from pathlib import Path

HERE = Path(__file__).resolve().parent
WORK = HERE.parent
START, END = "<!-- memory-records:start (generated by registry/import_memory_records.py; do not edit by hand) -->", "<!-- memory-records:end -->"
WS = re.compile("/" + "workspaces/[^\\s`'\")]*" + "|" + "/" + r"\.claude-" + "science/[^\\s`'\")]*")
MONEY_ROWS = {"mem_68cc74b3609a"}          # the user's spending amounts (verifier B4 rule)
MONEY = re.compile(r"\$\s?\d[\d,.]*(\s?/\s?h)?")
RESTRICTED = re.compile(r"(?i)FPPM|confidential|internal-v1|fuel-tables\.json|LOCAL-ONLY|\bUlich\b|\bEHM\b|MH371[^.]{0,40}ACARS|ACARS[^.]{0,40}MH371|mh371-acars|avionics_training|avionics_try|slideshare_avionics|Avionics Handbook")
TOPIC_MODULE = {"core-eof": "core", "seabed-search": "searched-areas", "pleiades": "pleiades", "debris-drift": "drift", "descent-6dof": "end-of-flight",
                "coordination": "project", "fuel": "core", "figures-style": "project", "other": "project", "paper": "paper", "ocean-data": "drift",
                "drive": "project", "git-repo": "project", "platform": "project", "literature": "project"}
PREFIX = {"core": "core", "end-of-flight": "eof", "drift": "drift", "settling": "settling", "searched-areas": "searched", "pleiades": "pleiades",
          "composer": "composer", "paper": "paper", "project": "project"}
VERIFIER_FIXES = {   # independent verifier, verifier-failures-2026-10-25.csv, track B, check B3
    "mem_2ffa247ff5bf": {"status": "PARTIAL", "corrected_text": "Third lowest of 135 R600 bursts (2 lower, 1.5 %; rank 2.2 %); one of 4 R600 bursts with BER > 0.",
                         "finding": "FAIL: raw SITA SU Log recount gives rank 3 of 135, not 'lowest 1.5%'; caveat restored; PARTIAL until the wording is fixed."},
    "mem_c43071d1047b": {"status": "VERIFIED", "corrected_text": "", "finding": "FAIL fixed: the 'correction' was wrong; ATSB 2017 printed p. 83 (debris field) and p. 89 (detection test) as the original row says. Original text restored."},
    "mem_98996cd144b1": {"append_source": "Crossref 10.1017/S0373463325000220: Journal of Navigation 77(5-6), 658-676, 2024.", "finding": "MINOR fixed: Crossref details added."},
    "mem_561c642205db": {"append_source": "Royer: Bay of Bengal / Myanmar survey statement also on PDF p. 4.", "finding": "MINOR fixed: p. 4 added to the citation."},
    "mem_3c74d2454b84": {"append_source": "Tracked copy: ISO Sept 28 Status/code/main/.sources/davey-2016/paper.pdf (engine/.sources/davey-2016/paper.pdf is not on the branch).", "finding": "MINOR fixed: path corrected."},
    "mem_ea1ebda0e8af": {"finding": "MINOR: not in the external-facts CSV; status taken from the change list."},
    "mem_bde51d87799f": {"finding": "MINOR: not in the external-facts CSV; status taken from the change list."},
    "mem_fc6fbd90420d": {"finding": "MINOR: not in the external-facts CSV; status taken from the change list."},
}


def clean(mid, text, export_vid):
    flags = []
    if RESTRICTED.search(text):
        return (f"[text withheld from the repository: it names a restricted source (results/restricted-sources-ledger.md). "
                f"Full text: memory export artifact version {export_vid}, row {mid}.]"), ["withheld_restricted"]
    if WS.search(text):
        text = WS.sub("<session workspace path>", text); flags.append("workspace_path_replaced")
    if mid in MONEY_ROWS:
        text = MONEY.sub("<amount removed>", text); flags.append("amounts_removed")
    return text, flags


def cell(s):
    return (s or "").replace("|", "/").replace("\n", " ").strip()


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--export", required=True); ap.add_argument("--changes", required=True); ap.add_argument("--facts", required=True)
    ap.add_argument("--export-vid", default="ba131e4c-350c-4db5-8b56-a61b3f2772f9")
    a = ap.parse_args()
    exp = {}
    raw = open(a.export, "rb").read()
    for l in raw.decode().splitlines():
        if l.strip():
            d = json.loads(l); exp[d["id"]] = d
    ch = list(csv.DictReader(open(a.changes)))
    facts = {r["mem_id"]: r for r in csv.DictReader(open(a.facts))}
    stats = collections.Counter()
    # ---------- registry notes ----------
    nd = HERE / "memory-notes"; nd.mkdir(exist_ok=True)
    by_topic = collections.defaultdict(list)
    for r in ch:
        if r["action"] != "move-to-registry":
            continue
        if r["target_path"].startswith("hypothesis/hydroacoustics"):
            stats["registry_rows_hydro_not_written"] += 1; continue
        mid = r["mem_id"]; e = exp[mid]
        text, flags = clean(mid, e["body"], a.export_vid)
        for f in flags:
            stats["registry_" + f] += 1
        topic = r["topic"] or "other"
        mod = TOPIC_MODULE.get(topic, "project")
        topic_note = f"{PREFIX[mod]}.memnote.{topic}"
        by_topic[topic].append({
            "mem_id": mid, "registry_entry": r["registry_entry"] or topic_note,
            "link": "existing entry (memory track)" if r["registry_entry"] else "topic note entry (no entry matched)",
            "topic": topic, "module": mod, "written_utc": r["written_utc"], "memory_evidence_tag": r["orig_evidence"], "marker": r["marker"],
            "original_text": text, "text_flags": flags,
            "verification_status": r["verification_status"], "verified_by": cell(r["verified_by"]), "verification_evidence": cell(r["evidence"]),
            "nature": "record of what memory said; not a verified fact"})
        stats["registry_rows_written"] += 1
        stats["registry_rows_linked_existing" if r["registry_entry"] else "registry_rows_linked_topic_note"] += 1
    index = {"what": "Memory rows moved to the registry, 25 Oct 2026. Records of what memory said; not verified facts.",
             "inputs": {"export_artifact_version": a.export_vid, "export_sha256": hashlib.sha256(raw).hexdigest()},
             "topics": {}, "stats": {}}
    for t, rows in sorted(by_topic.items()):
        rows.sort(key=lambda x: (x["written_utc"], x["mem_id"]))
        with open(nd / f"{t}.jsonl", "w", encoding="utf-8") as fh:
            for x in rows:
                fh.write(json.dumps(x, ensure_ascii=False) + "\n")
        index["topics"][t] = {"module": TOPIC_MODULE.get(t, "project"), "file": f"memory-notes/{t}.jsonl", "rows": len(rows),
                              "topic_note_entry": f"{PREFIX[TOPIC_MODULE.get(t, 'project')]}.memnote.{t}",
                              "rows_linked_to_topic_note": sum(1 for x in rows if x["link"].startswith("topic")),
                              "status_counts": dict(collections.Counter(x["verification_status"] for x in rows))}
    links = collections.defaultdict(list)
    for t, rows in by_topic.items():
        for x in rows:
            links[x["registry_entry"]].append(x["mem_id"])
    index["links"] = {k: sorted(v) for k, v in sorted(links.items())}
    # ---------- citation ledgers ----------
    ledgers = collections.defaultdict(list)
    for r in ch:
        if r["action"] != "move-to-citation-ledger":
            continue
        tgt = r["ledger_target"].split(" (")[0]
        if "hydroacoustics-references" in tgt:
            stats["ledger_rows_hydro_not_written"] += 1; continue
        mid = r["mem_id"]; f = facts.get(mid, {}); fx = VERIFIER_FIXES.get(mid, {})
        text, flags = clean(mid, exp[mid]["body"], a.export_vid)
        for fl in flags:
            stats["ledger_" + fl] += 1
        if fx.get("corrected_text"):
            text = "[SUPERSEDED WORDING - the independent verifier found this text wrong; use the corrected text column] " + text
            stats["ledger_rows_marked_superseded_wording"] += 1
        status = fx.get("status") or f.get("d_status") or r["verification_status"]
        corr = fx["corrected_text"] if "corrected_text" in fx else (f.get("corrected_text") or r["new_text"])
        corr, _ = clean(mid, corr, a.export_vid) if corr else ("", [])
        src = f.get("source", "")
        if fx.get("append_source"):
            src = (src + " " if src else "") + fx["append_source"]
        ledgers[tgt].append({"mem_id": mid, "written": r["written_utc"], "text": text, "status": status, "source": src,
                             "method": f.get("method") or r["verified_by"], "evidence": f.get("evidence") or r["evidence"],
                             "corrected": corr, "verifier": fx.get("finding", "")})
        stats["ledger_rows_written"] += 1
    created = []
    for tgt, rows in sorted(ledgers.items()):
        p = WORK.parent / tgt
        rows.sort(key=lambda x: (x["written"], x["mem_id"]))
        sec = [START, "", "## External facts moved from memory (25 October 2026)", "",
               "These rows are records of what project memory said about external sources. They are not verified facts unless the",
               "status column says VERIFIED or CORRECTED, and even then the check was the memory track's check of the held source.",
               "Status values: VERIFIED (claim found in the source), CORRECTED (claim corrected against the source; use the corrected",
               "text), PARTIAL (part of the claim found), UNVERIFIABLE (no held copy, or the claim was not found). The last column gives",
               "the finding of the independent verifier of 25 October 2026 where there is one. Text that names a restricted source is",
               "withheld here; the memory export row holds it.", "",
               "| mem_id | written (UTC) | memory text | status | source | method and evidence | corrected text | verifier |", "|---|---|---|---|---|---|---|---|"]
        for x in rows:
            sec.append("| " + " | ".join(cell(v)[:900] for v in (f"`{x['mem_id']}`", x["written"], x["text"], x["status"], x["source"],
                                                               (x["method"] + "; " + x["evidence"]).strip("; "), x["corrected"], x["verifier"])) + " |")
        sec += ["", END]
        if p.exists():
            t = p.read_text()
            if START in t:
                t = t[:t.index(START)] + "\n".join(sec) + t[t.index(END) + len(END):]
            else:
                t = t.rstrip("\n") + "\n\n" + "\n".join(sec) + "\n"
        else:
            name = p.stem.replace("-references", "")
            t = (f"# {name.capitalize()} references\n\nCitation ledger of the {name} module. Made on 25 October 2026 by the registry track to hold the\n"
                 "external-fact rows that moved out of memory. Add new references above the generated section.\n\n" + "\n".join(sec) + "\n")
            created.append(tgt)
        p.write_text(t)
        stats[f"ledger:{tgt}"] = len(rows)
    index["citation_ledgers"] = {k: len(v) for k, v in sorted(ledgers.items())}
    index["citation_ledgers_created"] = created
    index["stats"] = dict(stats)
    json.dump(index, open(nd / "index.json", "w"), indent=1, ensure_ascii=False)
    print(json.dumps(index["stats"], indent=1))


if __name__ == "__main__":
    main()
