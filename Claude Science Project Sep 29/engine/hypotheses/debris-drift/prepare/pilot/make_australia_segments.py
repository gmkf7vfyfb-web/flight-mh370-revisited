"""Australian coastal detection segments by ABS remoteness class (Pete, 12 Oct 2026: finds are less likely where
there are fewer people; all Australian coasts). Source: ABS ASGS Edition 3 Remoteness Areas 2021, RA_2021_AUST_GDA2020
(GDA2020 taken as WGS84; difference < 2 m). Method: the coastline is the exterior boundary of the union of the land RA polygons (slivers closed, lake shores dropped);
each class's coast is sampled every ~1 km, binned to 0.2 deg cells, and each cell takes its majority class; cells are
merged into row runs and written as segment boxes [lon_min, lon_max, lat_min, lat_max], dilated by 0.05 deg.
Segments = region x class: regions WA (state 5), south (SA 4, Vic 2, Tas 6), north-east (NT 7, Qld 3, NSW 1, ACT 8) and
Indian Ocean territories (Christmas Island, Cocos (Keeling): state 9 west of 110 E); classes city+inner (x0, x1),
outer regional (x2), remote+very remote (x3, x4). Order: city+inner, outer, remote (first match wins at shared edges).
Usage: python make_australia_segments.py <RA shp> <out.toml> <out-summary.csv>"""
import sys, collections
import numpy as np, shapely, pyogrio.raw as raw
shp, out_toml, out_csv = sys.argv[1:4]
meta, _, geom, fields = raw.read(shp)
f = dict(zip(meta["fields"], fields)); g = shapely.from_wkb(geom)
code = f["RA_CODE21"]; ste = f["STE_CODE21"]
land = [i for i, c in enumerate(code) if g[i] is not None and c[-1] in "01234"]
simp = {i: shapely.simplify(g[i], 0.005) for i in land}
# Close slivers between simplified neighbours, then keep exterior rings only (lake shores are interior rings).
union = shapely.union_all([simp[i] for i in land]).buffer(0.02).buffer(-0.02)
coast = shapely.union_all([shapely.LineString(pg.exterior.coords) for pg in getattr(union, 'geoms', [union])])
CLS = {"0": "city-inner", "1": "city-inner", "2": "outer", "3": "remote", "4": "remote"}
def region(i, x):
    s = ste[i]
    if s == "9": return "indian-ocean-territories" if x < 110 else None
    return {"5": "wa", "4": "south", "2": "south", "6": "south"}.get(s, "north-east")
D = 0.2; cells = collections.defaultdict(collections.Counter); km = collections.Counter()
for i in land:
    c = shapely.intersection(simp[i].boundary, shapely.buffer(coast, 0.03))
    if c.is_empty: continue
    pts = shapely.get_coordinates(shapely.segmentize(c, 0.009))  # ~1 km
    if len(pts) == 0: continue
    for x, y in pts:
        r = region(i, x)
        if r is None: continue
        key = f"{r}:{CLS[code[i][-1]]}"; cells[(int(np.floor(y / D)), int(np.floor(x / D)))][key] += 1; km[key] += 1
own = {k: v.most_common(1)[0][0] for k, v in cells.items()}
segs = sorted(set(own.values()), key=lambda s: (["city-inner", "outer", "remote"].index(s.split(":")[1]), s))
out = ["# Generated by prepare/pilot/make_australia_segments.py from ABS RA 2021 (see its docstring). PROVISIONAL.\n"]
rows = []
for s in segs:
    cs = sorted(k for k, v in own.items() if v == s); boxes = []
    for r in sorted({k[0] for k in cs}):
        js = sorted(k[1] for k in cs if k[0] == r); a = js[0]; b = js[0]
        for j in js[1:] + [None]:
            if j is not None and j == b + 1: b = j; continue
            boxes.append([round(a * D - 0.05, 3), round((b + 1) * D + 0.05, 3), round(r * D - 0.05, 3), round((r + 1) * D + 0.05, 3)])
            if j is not None: a = b = j
    name = "AU-" + s.replace(":", "-")
    out.append(f'[[hypotheses.debris-drift.segments]]\nname = "{name}"\nboxes = [{", ".join("[" + ", ".join(map(str, bx)) + "]" for bx in boxes)}]\n')
    rows.append((name, len(cs), len(boxes), km[s]))
open(out_toml, "w").write("\n".join(out))
with open(out_csv, "w") as fh:
    fh.write("segment,cells_0p2deg,boxes,coast_samples_about_km\n"); [fh.write(f"{a},{b},{c},{d}\n") for a, b, c, d in rows]
print("\n".join(f"{a}: {b} cells, {c} boxes, ~{d} km" for a, b, c, d in rows))
